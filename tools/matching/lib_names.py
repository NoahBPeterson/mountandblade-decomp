#!/usr/bin/env python3
"""Write symbols/lib_names.txt from work/oss/crt_matches.csv (libresolve.py output for the VC7.1
libcmt/libcpmt objects): one `<va> lib_crt::<symbol>` line per unique byte-exact placement.
The equivalence resolver and status.py read this file.
usage: lib_names.py"""
import csv, os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
rows = sorted({(int(r["va"], 16), r["name"], r["obj"]) for r in csv.DictReader(open(os.path.join(ROOT, "work/oss/crt_matches.csv")))
               if r["status"] == "unique"})
with open(os.path.join(ROOT, "symbols", "lib_names.txt"), "w") as f:
    f.write("# Generated by tools/matching/lib_names.py: byte-exact with VC7.1 Toolkit libcmt/libcpmt (cl 13.10.3052)\n")
    for va, name, obj in rows:
        f.write("%08x lib_crt::%s  # %s\n" % (va, name, os.path.basename(obj)))
print("wrote %d names" % len(rows))
